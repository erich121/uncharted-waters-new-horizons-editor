"""Bundled starting settings; native ROM references stay unchanged."""
import json
from pathlib import Path


def manifest():
    """Read a detached copy of the supplied complete default project."""
    path = Path(__file__).resolve().parent / 'assets' / 'default-settings.json'
    return json.loads(path.read_text(encoding='utf-8'))


def new_project(source):
    """Use bundled settings only for fresh app setups, never saved projects."""
    from backend import ShipProject
    project = ShipProject(source)
    project.load_manifest(manifest())
    return project


def preset_document():
    """The supplied presets and retired names, detached from local storage."""
    path = Path(__file__).resolve().parent / 'assets' / 'default-presets.json'
    return json.loads(path.read_text(encoding='utf-8'))


def provided_names():
    return tuple(preset_document()['presets']) + ('Full Randomizer',)


def preset_descriptions():
    data = preset_document()
    result = {name: data['descriptions'].get(name, '') for name in data['presets']}
    result['Full Randomizer'] = 'Shuffle mate ports, mate/captain names, attributes and skills, goods, items and original-ship building locations, with the bundled discovery set.'
    return result


def startup_project(source):
    """Open without activating the supplied custom discovery pool."""
    from discovery_content import stock_id
    project = new_project(source)
    project.custom_discoveries = False
    project.discovery_entries = {}
    project.discovery_identities = [stock_id(slot) for slot in range(98)]
    project.discovery_rewrites = False
    project.discovery_easy = False
    return project


def library_document(source, *, _legacy=False, _previous=False):
    """Keep supplied content; group only the original ships and discoveries.

    The legacy path identifies entries generated by the earlier overbroad seed
    so an existing Library can be repaired without deleting user content.
    """
    if not _legacy and not _previous:
        path = Path(__file__).resolve().parent / 'assets' / 'default-library.json'
        return json.loads(path.read_text(encoding='utf-8'))
    import uuid
    from backend import ShipProject
    from content_library import FORMAT, capture_ship
    from discovery_content import capture as capture_discovery
    from item_library import capture as capture_item
    stock = ShipProject(source)
    originals, entries, seen, identities, collections = {}, [], {}, set(), {}

    def fingerprint(entry):
        return json.dumps({k: v for k, v in entry.items() if k != 'id'}, sort_keys=True, separators=(',', ':'))

    snapshots = [('Bundled content', manifest()), *preset_document()['presets'].items()]
    for name, snapshot in snapshots:
        project = ShipProject(source)
        project.load_manifest(snapshot)
        candidates = [capture_ship(project, i, variant=False) for i in range(len(project.ships))
                      if _legacy or i >= 25 or not project.ship_identities[i].startswith('stock-ship:')]
        candidates += [capture_discovery(project, i) for i in (range(98) if _legacy else sorted(project.discovery_entries))]
        if _legacy and (project.item_edits or project.item_price_edits):
            from items import catalogue
            candidates += [capture_item(project, row['id']) for row in catalogue(project.rom)]
        members = []
        for entry in candidates:
            kind = entry['kind']
            if kind == 'ship':
                slot = next((i for i, identity in enumerate(project.ship_identities) if identity == entry['id']), None)
                origin = slot if slot is not None and slot < 25 else None
                capture = lambda: capture_ship(stock, origin, variant=False)
            elif kind == 'discovery':
                origin = int(entry['replaces'].rsplit(':', 1)[1])
                capture = lambda: capture_discovery(stock, origin)
            else:
                origin = entry['item_id']
                capture = lambda: capture_item(stock, origin)
            key = fingerprint(entry)
            if origin is not None:
                original_key = (kind, origin)
                if original_key not in originals:
                    originals[original_key] = fingerprint(capture())
                if key == originals[original_key]:
                    continue
            if key not in seen:
                identity = entry['id']
                if identity.startswith('stock-') or identity in identities:
                    identity = str(uuid.uuid5(uuid.NAMESPACE_URL, 'new-horizons-bundled:' + key))
                entry['id'] = identity
                identities.add(identity)
                entries.append(entry)
                seen[key] = identity
            if seen[key] not in members:
                members.append(seen[key])
        if members:
            collections[name] = members
    if not _legacy:
        originals = [capture_ship(stock, i, variant=False) for i in range(25)]
        originals += [capture_discovery(stock, i) for i in range(98)]
        from items import catalogue
        originals += [capture_item(stock, row['id']) for row in catalogue(stock.rom)]
        entries = originals + entries
        collections = ({'Stock Game': [e['id'] for e in originals], **collections} if _previous else
                       {'Stock Ships': [e['id'] for e in originals if e['kind']=='ship'],
                        'Stock Discoveries': [e['id'] for e in originals if e['kind']=='discovery']})
    return dict(format=FORMAT, version=1, entries=entries, collections=collections)


def previous_library_document():
    """Recognize shipped defaults without treating users' variants as defaults."""
    path = Path(__file__).resolve().parent / 'assets' / 'previous-library-defaults.json'
    return json.loads(path.read_text(encoding='utf-8'))
